// Keeps the <link rel="modulepreload"> / data preload hints of index.html in line with the real import graph.
// Without them the browser discovers the 60+ modules level by level (each level costs a round trip); with them it asks for all at once.
// `npm run build:offline` runs this first; tests/preload-hints.test.js fails when the hints in index.html are out of date.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export const START = '<!-- preload-hints:start (generated by scripts/preload-hints.js) -->';
export const END = '<!-- preload-hints:end -->';
/**
 * Entry point whose whole static import graph is needed before the guide can draw. The account code (account.js, auth.js, the Auth0 SDK,
 * cloud-sync) is NOT here: with the account disabled in assets/auth-config.js none of it may be requested. main.js starts it itself once the config says so.
 */
export const ENTRIES = ['js/main.js'];
/** The tiny config main.js imports dynamically at start. */
export const EXTRA_MODULES = ['assets/auth-config.js'];
/** Data every start fetches before anything can render (the city files depend on the date, so they are fetched from main.js). */
export const DATA_FILES = ['data/journey.json', 'data/global/tips.json', 'data/global/phrases.json', 'data/global/dishes.json', 'data/global/dish-credits.json', 'data/global/lodging.json', 'data/global/checklist.json'];

const specifiers = (source) => [...source.matchAll(/^\s*(?:import|export)\s[^'"]*?from\s+['"](\.[^'"]+)['"]|^import\s+['"](\.[^'"]+)['"]/gm)].map((m) => m[1] ?? m[2]);

export async function moduleGraph(root = process.cwd()) {
  const seen = new Set();
  const visit = async (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const source = await readFile(path.join(root, file), 'utf8');
    for (const spec of specifiers(source)) await visit(path.posix.normalize(path.posix.join(path.posix.dirname(file), spec)));
  };
  for (const entry of ENTRIES) await visit(entry);
  return [...seen, ...EXTRA_MODULES].sort();
}

export async function hintBlock(root = process.cwd()) {
  const modules = await moduleGraph(root);
  return [
    START,
    ...modules.map((file) => `  <link rel="modulepreload" href="${file}">`),
    ...DATA_FILES.map((file) => `  <link rel="preload" as="fetch" href="${file}" crossorigin>`),
    `  ${END}`
  ].join('\n');
}

export function withHints(html, block) {
  const pattern = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
  if (!pattern.test(html)) throw new Error('index.html has no preload-hints block');
  return html.replace(pattern, () => block.replace(/^ {2}(?=<!-- preload-hints:end)/, ''));
}

export async function writeHints(root = process.cwd()) {
  const file = path.join(root, 'index.html');
  const html = await readFile(file, 'utf8').catch(() => null);
  if (!html || !html.includes(START)) return false; // a site without the block (or the test fixtures) has nothing to keep in line
  const next = withHints(html, await hintBlock(root));
  if (next !== html) await writeFile(file, next);
  return next !== html;
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) {
  console.log((await writeHints()) ? 'index.html: preload hints updated.' : 'index.html: preload hints already up to date.');
}
